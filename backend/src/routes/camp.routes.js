const express = require("express");
const { requireAuth, optionalAuth } = require("../middleware/auth.middleware");
const controller = require("../controllers/camp.controller");
const community = require("../controllers/community.controller");
const router = express.Router();
router.get("/", controller.listCamps);
router.get("/mine", requireAuth, (req, res) => { req.mine = true; return controller.listCamps(req, res); });
router.get("/registrations/mine", requireAuth, controller.myRegistrations);
router.get("/registrations/manage", requireAuth, controller.organizationRegistrations);
router.get("/invitations/mine", requireAuth, community.listInvitations);
router.patch("/invitations/:invitationId", requireAuth, (req, res) => { req.params.id = req.params.invitationId; return community.updateInvitation(req, res); });
router.post("/", requireAuth, controller.createCamp);
router.get("/:id", optionalAuth, controller.getCamp);
router.patch("/:id", requireAuth, controller.updateCamp);
router.post("/:id/registrations", requireAuth, controller.createRegistration);
router.delete("/:id/registrations/mine", requireAuth, controller.cancelMyRegistration);
router.get("/:id/registrations", requireAuth, controller.listRegistrations);
router.patch("/:id/registrations/:registrationId", requireAuth, controller.updateRegistration);
router.get("/:campId/feedback", community.feedbackList);
router.post("/:campId/feedback", requireAuth, community.submitFeedback);
router.post("/:campId/invitations", requireAuth, community.sendInvitation);
module.exports = router;
